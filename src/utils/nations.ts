export function normalizeNation(raw?: string): NormalizedNation {
  const trimmed = (raw ?? "").trim();
  if (!trimmed) {
    return { key: "unknown", labelPt: "Internacional", flag: "🏳️", confed: "UEFA" };
  }
  const aliasKey = ALIAS_TO_KEY[trimmed.toLowerCase()];
  if (aliasKey && CANONICAL_NATIONS[aliasKey]) {
    return { key: aliasKey, ...CANONICAL_NATIONS[aliasKey] };
  }
  return {
    key: trimmed.toLowerCase().replace(/\s+/g, "_"),
    labelPt: trimmed,
    flag: "🏳️",
    confed: "UEFA",
  };
}
